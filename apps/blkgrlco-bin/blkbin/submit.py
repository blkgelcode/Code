"""Dry run, apply and undo for renames + moves.

Rules:
- Never delete a file. Never overwrite one: a taken name gets -2, -3, ...
- Only os.rename inside the project folder (same drive, so nothing is copied).
- A journal is written before each step, so undo works even after a crash.
- Every move is appended to _bin-log.csv (timestamp, old path, new path).
"""
from __future__ import annotations

import csv
import datetime as dt
import errno
import hashlib
import json
import os
import shutil
from pathlib import Path

from . import media, settings as settings_mod

LOG_NAME = "_bin-log.csv"
MASTER_NAME = "_footage-master.md"
MASTER_MARK = "<!-- generated by BLKGRLCO Bin -->"


class SubmitError(Exception):
    pass


# ---- helpers ------------------------------------------------------------------

def _taken(path: Path, claimed: set, own: Path | None) -> bool:
    """True if the name is used on disk (case-insensitively, like macOS) or claimed in this plan."""
    if path.as_posix().lower() in claimed:
        return True
    parent = path.parent
    if not parent.exists():
        return False
    for sibling in os.listdir(parent):
        if sibling.lower() == path.name.lower():
            other = parent / sibling
            if own is not None and other.exists() and own.exists() and os.path.samefile(other, own):
                return False
            return True
    return False


def free_name(path: Path, claimed: set, own: Path | None = None) -> Path:
    if not _taken(path, claimed, own):
        return path
    stem, ext = path.stem, path.suffix
    n = 2
    while True:
        candidate = path.with_name(f"{stem}-{n}{ext}")
        if not _taken(candidate, claimed, own):
            return candidate
        n += 1


def _now() -> str:
    return dt.datetime.now().astimezone().isoformat(timespec="seconds")


def _journal_dir(project) -> Path:
    d = project.state_dir / "submits"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _write_journal(project, journal: dict) -> None:
    p = _journal_dir(project) / f"{journal['id']}.json"
    tmp = p.with_suffix(".tmp")
    tmp.write_text(json.dumps(journal, indent=1))
    tmp.replace(p)


def _journals(project) -> list[dict]:
    out = []
    d = project.state_dir / "submits"
    if not d.exists():
        return out
    for p in sorted(d.glob("*.json")):
        try:
            out.append(json.loads(p.read_text()))
        except ValueError:
            continue
    return out


def latest_undoable(project) -> dict | None:
    for j in reversed(_journals(project)):
        if j.get("undone"):
            continue
        if any(op.get("done") for op in j["ops"]):
            return j
    return None


# ---- dry run ----------------------------------------------------------------

def plan(project) -> dict:
    cfg = settings_mod.load()
    project.refresh()
    with project.lock:
        props = project.proposals(cfg)
        ops = []
        claimed: set = set()
        skipped = []
        for e in sorted(project.entries(), key=lambda x: x["path"].lower()):
            status = project.status(e, cfg, props)
            if status != "included":
                if status in ("waiting", "analyzing", "error"):
                    skipped.append({"path": e["path"], "reason": status})
                continue
            src = project.root / e["path"]
            want = project.root / project.target_dir(e, cfg) / props[e["fid"]]
            dst = free_name(want, claimed, own=src)
            if dst == src:
                continue
            claimed.add(dst.as_posix().lower())
            ops.append({
                "fid": e["fid"],
                "src": project.rel(src),
                "dst": project.rel(dst),
                "name": props[e["fid"]],
                "category": e["category"],
                "suffixed": dst.name != want.name,
            })
    digest = hashlib.sha1(json.dumps(ops, sort_keys=True).encode()).hexdigest()[:12]
    result = {"plan_id": digest, "ops": ops, "skipped": skipped, "project": str(project.root)}
    project.last_plan = result
    return result


# ---- apply ------------------------------------------------------------------

def apply(project, plan_id: str) -> dict:
    fresh = plan(project)
    if fresh["plan_id"] != plan_id:
        raise SubmitError("The folder or your choices changed since the dry run. Review the new list and confirm again.")
    if not fresh["ops"]:
        raise SubmitError("Nothing to change.")
    cfg = settings_mod.load()
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    journal = {
        "id": f"{stamp}-{plan_id}", "created": _now(), "project": str(project.root),
        "ops": [dict(op, done=False) for op in fresh["ops"]], "created_dirs": [],
        "master": None, "undone": False, "complete": False,
    }
    _write_journal(project, journal)
    log_rows = []
    errors = []
    with project.lock:
        for op in journal["ops"]:
            src = project.root / op["src"]
            dst = project.root / op["dst"]
            if not src.exists():
                errors.append(f"{op['src']}: file is gone, skipped")
                continue
            for parent in reversed(dst.relative_to(project.root).parents):
                d = project.root / parent
                if parent != Path(".") and not d.exists():
                    d.mkdir()
                    journal["created_dirs"].append(project.rel(d))
            # re-check right before the move: never overwrite
            if _taken(dst, set(), own=src):
                dst = free_name(dst, set(), own=src)
                op["dst"] = project.rel(dst)
            _write_journal(project, journal)
            try:
                os.rename(src, dst)
            except OSError as exc:
                if exc.errno == errno.EXDEV:
                    errors.append(f"{op['src']}: on a different drive, not moved")
                    continue
                errors.append(f"{op['src']}: {exc.strerror}")
                continue
            op["done"] = True
            op["at"] = _now()
            _write_journal(project, journal)
            log_rows.append([op["at"], str(src), str(dst), "submit", journal["id"]])
            e = project.state["files"].get(op["fid"])
            if e:
                e["path"] = op["dst"]
                e["applied"] = {"path": op["dst"], "name": op["name"], "category": op["category"]}
        append_log(project, log_rows)
        journal["master"] = write_master(project, cfg, journal["id"])
        journal["complete"] = True
        _write_journal(project, journal)
        project.save()
    project.refresh()
    done = [op for op in journal["ops"] if op.get("done")]
    return {"applied": len(done), "errors": errors, "journal": journal["id"], "ops": done}


def append_log(project, rows: list) -> None:
    if not rows:
        return
    p = project.root / LOG_NAME
    new = not p.exists()
    with open(p, "a", newline="") as f:
        w = csv.writer(f)
        if new:
            w.writerow(["timestamp", "old_path", "new_path", "action", "submit_id"])
        w.writerows(rows)


# ---- undo -------------------------------------------------------------------

def undo(project) -> dict:
    journal = latest_undoable(project)
    if not journal:
        raise SubmitError("There's no submit to undo.")
    restored, conflicts, log_rows = [], [], []
    with project.lock:
        for op in reversed(journal["ops"]):
            if not op.get("done") or op.get("undone"):
                continue
            src = project.root / op["src"]   # where it was
            dst = project.root / op["dst"]   # where it is now
            if not dst.exists():
                conflicts.append(f"{op['dst']}: not there anymore, left as is")
                continue
            if _taken(src, set(), own=dst):
                conflicts.append(f"{op['src']}: something else now has this name, left {op['dst']} where it is")
                continue
            src.parent.mkdir(parents=True, exist_ok=True)
            os.rename(dst, src)
            op["undone"] = True
            restored.append(op)
            log_rows.append([_now(), str(dst), str(src), "undo", journal["id"]])
            e = project.state["files"].get(op["fid"])
            if e:
                e["path"] = op["src"]
                e["applied"] = None
            _write_journal(project, journal)
        # remove only the folders this submit created, and only if empty
        left_dirs = []
        for rel in sorted(journal["created_dirs"], key=lambda r: r.count("/"), reverse=True):
            d = project.root / rel
            try:
                d.rmdir()
            except OSError:
                if d.exists():
                    left_dirs.append(rel)
        _restore_master(project, journal)
        append_log(project, log_rows)
        journal["undone"] = not conflicts
        journal["undone_at"] = _now()
        _write_journal(project, journal)
        project.save()
    project.refresh()
    return {"restored": len(restored), "conflicts": conflicts, "folders_kept": left_dirs,
            "ops": restored, "journal": journal["id"]}


# ---- _footage-master.md -------------------------------------------------------

def _history_dir(project) -> Path:
    d = project.state_dir / "history"
    d.mkdir(parents=True, exist_ok=True)
    return d


def write_master(project, cfg: dict, journal_id: str) -> dict:
    """Write _footage-master.md. The previous version is kept in .blkgrlco-bin/history."""
    p = project.root / MASTER_NAME
    record = {"existed": p.exists(), "backup": None}
    if p.exists():
        backup = _history_dir(project) / f"_footage-master.before-{journal_id}.md"
        shutil.copy2(p, backup)
        record["backup"] = project.rel(backup)
        if MASTER_MARK not in p.read_text(errors="ignore")[:300]:
            # a hand-written file with this name: leave it, write ours next to it
            p = free_name(p, set())
            record = {"existed": False, "backup": None, "written_as": project.rel(p)}
    p.write_text(render_master(project, cfg))
    record["path"] = project.rel(p)
    return record


def _restore_master(project, journal: dict) -> None:
    rec = journal.get("master")
    if not rec:
        return
    current = project.root / rec["path"]
    if not current.exists():
        return
    # the submitted version is kept, not deleted
    current.replace(_history_dir(project) / f"_footage-master.undone-{journal['id']}.md")
    if rec.get("existed") and rec.get("backup"):
        shutil.copy2(project.root / rec["backup"], current)


def render_master(project, cfg: dict) -> str:
    rows = []
    order = {c["id"]: i for i, c in enumerate(cfg["categories"])}
    entries = [e for e in project.entries() if e.get("state") == "done"]
    entries.sort(key=lambda e: (order.get(e.get("category"), 99), e["path"].lower()))
    for e in entries:
        cat = settings_mod.category(cfg, e.get("category"))
        desc = ((e.get("analysis") or {}).get("description") or "").replace("|", "/").replace("\n", " ")
        rows.append("| {} | {} | {} | {} | {} |".format(
            Path(e["path"]).name,
            cat["name"] if cat else "—",
            media.human_duration(e.get("duration")) if e["kind"] != "photo" else "—",
            (e.get("speech") or {}).get("level", "—"),
            desc or "—",
        ))
    when = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    return "\n".join([
        MASTER_MARK,
        f"# Footage master: {project.name}",
        "",
        f"_{len(rows)} clips · updated {when} by BLKGRLCO Bin_",
        "",
        "| Clip | Category | Duration | Speech | Description |",
        "|---|---|---|---|---|",
        *rows,
        "",
    ])
